// Usability regressions reported from real phone use. Runs on a touch phone viewport.
// Usage: npx vite preview --port 4173 (other terminal) → node e2e/usability.mjs
import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'

const URL = process.env.URL ?? 'http://localhost:4173/'
const EDGE = process.env.EDGE ?? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'
const SHOTS = 'e2e/shots'
mkdirSync(SHOTS, { recursive: true })
const results = [], errors = []
const check = (n, c, x = '') => { results.push([c ? 'PASS' : 'FAIL', n, x]); if (!c) process.exitCode = 1 }

const browser = await chromium.launch({ executablePath: EDGE })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true, locale: 'pt-BR' })
const page = await ctx.newPage()
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
await page.clock.install({ time: new Date(2026, 10, 18, 12, 0, 0) })
await page.goto(URL)
await page.evaluate(() => { localStorage.clear() })
await page.reload()
await page.getByRole('dialog', { name: 'Boas-vindas' }).getByRole('button', { name: 'Agora não' }).click()
const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('tdah-clock:v1')))

// ---- 1. Routine: new steps can be added (button, Enter) and a typed-but-not-added step is kept on Save
await page.goto(URL + '#/routines')
await page.getByRole('button', { name: 'Nova' }).click()
await page.getByLabel('Nome', { exact: true }).fill('Antes de sair')
await page.getByLabel('Novo passo', { exact: true }).fill('Pegar a carteira')
await page.getByLabel('Minutos do novo passo').fill('2')
check('routine: Adicionar button visible', await page.getByRole('button', { name: 'Adicionar' }).isVisible())
await page.getByRole('button', { name: 'Adicionar' }).click()
check('routine: step added with button', await page.getByLabel('Passo 1', { exact: true }).inputValue() === 'Pegar a carteira')
check('routine: input cleared + refocused', (await page.getByLabel('Novo passo', { exact: true }).inputValue()) === '' && await page.getByLabel('Novo passo', { exact: true }).evaluate((el) => el === document.activeElement))
await page.getByLabel('Novo passo', { exact: true }).fill('Pegar as chaves')
await page.getByLabel('Novo passo', { exact: true }).press('Enter')
check('routine: step added with Enter (2 fields in form)', await page.getByLabel('Passo 2', { exact: true }).isVisible())
await page.getByLabel('Minutos do passo 2').fill('1')
await page.getByLabel('Novo passo', { exact: true }).fill('Conferir o fogão')
await page.screenshot({ path: `${SHOTS}/u1-routine-editor.png` })
await page.locator('.sheet').getByRole('button', { name: 'Salvar' }).click()
let s = await state()
const r = s.routines.find((x) => x.name === 'Antes de sair')
check('routine: saved with all 3 steps (pending one kept)', r?.steps.length === 3, JSON.stringify(r?.steps.map((x) => x.text)))
check('routine: step minutes editable', r?.steps[0].minutes === 2 && r?.steps[1].minutes === 1)

// ---- 2. Alarm: minute-by-minute time
await page.goto(URL + '#/clock')
await page.getByRole('button', { name: 'Novo alarme' }).click()
const minutes = page.getByLabel('minutos', { exact: true })
await page.getByLabel('Aumentar minutos').click()
await page.getByLabel('Aumentar minutos').click()
await page.getByLabel('Aumentar minutos').click()
check('alarm: ▲ steps exactly 1 minute', (await minutes.inputValue()) === '03', await minutes.inputValue())
await minutes.click()
await page.keyboard.type('47')
await page.getByLabel('hora', { exact: true }).click()
await page.keyboard.type('6')
await page.getByLabel('Nome', { exact: true }).click()
check('alarm: typed 06:47', (await page.getByLabel('hora', { exact: true }).inputValue()) === '06' && (await minutes.inputValue()) === '47')
await page.getByRole('button', { name: '+1 min' }).click()
check('alarm: +1 min chip → 06:48', (await minutes.inputValue()) === '48')
// hold ▼ to scroll quickly
const down = page.getByLabel('Diminuir minutos')
const box = await down.boundingBox()
await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
await page.mouse.down(); await page.clock.runFor(1500); await page.mouse.up()
const afterHold = Number(await minutes.inputValue())
check('alarm: holding ▼ repeats', afterHold < 46, `→ ${afterHold}`)
await minutes.click(); await page.keyboard.type('59'); await page.getByLabel('Aumentar minutos').click()
check('alarm: minutes wrap 59 → 00', (await minutes.inputValue()) === '00')
await minutes.click(); await page.keyboard.type('31'); await page.getByLabel('Nome', { exact: true }).fill('Remédio')
await page.screenshot({ path: `${SHOTS}/u2-alarm-editor.png` })
await page.locator('.sheet').getByRole('button', { name: 'Salvar' }).click()
s = await state()
check('alarm: saved 06:31', s.alarms.some((a) => a.label === 'Remédio' && a.time === '06:31'), JSON.stringify(s.alarms.map((a) => a.time)))

// ---- 3. Timer: seconds precision
await page.getByRole('button', { name: 'Timer' }).click()
await page.getByLabel('minutos', { exact: true }).click(); await page.keyboard.type('0')
await page.getByLabel('segundos', { exact: true }).click(); await page.keyboard.type('45')
await page.getByLabel('Para quê?', { exact: false }).click()
await page.screenshot({ path: `${SHOTS}/u3-timer.png` })
check('timer: start button shows 45 s', await page.getByRole('button', { name: /Iniciar · 45 s/ }).isVisible())
await page.getByRole('button', { name: /Iniciar · 45 s/ }).click()
check('timer: running shows 00:45', await page.locator('.card .num', { hasText: '00:45' }).isVisible())
await page.getByRole('button', { name: '30 s' }).click()
check('timer: 30 s shortcut', await page.locator('.card .num', { hasText: '00:30' }).isVisible())
await page.clock.fastForward(31000); await page.waitForTimeout(100)
check('timer: 30 s timer rings', await page.locator('.ring-screen').isVisible())
await page.getByRole('button', { name: 'Ok' }).click()
await page.clock.fastForward(15000); await page.waitForTimeout(100)
check('timer: 45 s timer rings', await page.locator('.ring-screen').isVisible())
await page.getByRole('button', { name: 'Ok' }).click()

// ---- 4. Task editor: typing in later fields keeps focus (sheet used to steal it every keystroke)
await page.keyboard.press('n')
await page.getByLabel('Capturar').fill('Ligar para o banco')
await page.keyboard.press('Enter'); await page.keyboard.press('Escape')
await page.goto(URL + '#/tasks')
await page.getByRole('tab', { name: /Sem data/ }).click()
await page.getByText('Ligar para o banco').click()
const notes = page.locator('.sheet textarea')
await notes.click()
await page.keyboard.type('Pedir segunda via do cartão')
check('task: focus stays in notes while typing', (await notes.inputValue()) === 'Pedir segunda via do cartão', await notes.inputValue())
await page.getByLabel('Novo passo', { exact: true }).fill('Achar o número do cartão')
check('task: step Adicionar button', await page.locator('.sheet').getByRole('button', { name: 'Adicionar' }).isVisible())
await page.locator('.sheet').getByRole('button', { name: 'Adicionar' }).click()
// time via compact field
await page.getByRole('button', { name: /Hora: sem horário/ }).click()
await page.locator('.tf-pop').getByLabel('hora', { exact: true }).click(); await page.keyboard.type('15')
await page.locator('.tf-pop').getByLabel('minutos', { exact: true }).click(); await page.keyboard.type('07')
await page.locator('.tf-pop').getByRole('button', { name: 'Ok' }).click()
await page.screenshot({ path: `${SHOTS}/u4-task-editor.png` })
await page.locator('.sheet').getByRole('button', { name: 'Salvar' }).click()
s = await state()
const t = s.tasks.find((x) => x.title === 'Ligar para o banco')
check('task: notes, step and 15:07 saved', t?.notes === 'Pedir segunda via do cartão' && t?.steps?.length === 1 && t?.time === '15:07', JSON.stringify({ n: t?.notes, st: t?.steps?.length, tm: t?.time }))

// ---- 5. Leaving checklist: add item button
await page.getByRole('button', { name: 'Vou sair de casa' }).first().click()
await page.locator('.sheet').getByRole('button', { name: 'Editar' }).click()
await page.getByLabel('Novo item', { exact: true }).fill('Guarda-chuva')
await page.locator('.sheet').getByRole('button', { name: 'Adicionar' }).click()
check('leaving: item added via button', await page.locator('.sheet').getByText('Guarda-chuva').isVisible())
await page.keyboard.press('Escape')

// ---- 6. Settings: briefing time minute precision
await page.goto(URL + '#/settings')
await page.getByRole('button', { name: /Briefing da manhã: 07:30/ }).click()
await page.locator('.tf-pop').getByLabel('Aumentar minutos').click()
await page.locator('.tf-pop').getByRole('button', { name: 'Ok' }).click()
s = await state()
check('settings: briefing 07:31', s.settings.morningBrief === '07:31', s.settings.morningBrief)

// ---- 7. Android/browser Back closes the open overlay instead of changing the page underneath
const back = async () => { await page.evaluate(() => history.back()); await page.waitForTimeout(250) }
const sheetOpen = () => page.locator('.sheet').count().then((n) => n > 0)
await page.goto(URL + '#/tasks')
await page.goto(URL + '#/today')
await page.waitForTimeout(150)
await page.getByRole('button', { name: 'Lembrar de algo' }).first().click()
check('back: capture sheet opened', await sheetOpen())
await back()
check('back: Back closes capture sheet', !(await sheetOpen()))
check('back: page underneath unchanged (still Hoje)', page.url().endsWith('#/today'), page.url())
await back()
check('back: next Back goes to previous page', page.url().endsWith('#/tasks'), page.url())
// closing with the X must not leave a stale history entry
await page.getByRole('button', { name: 'Nova' }).click()
await page.locator('.sheet').getByRole('button', { name: 'Fechar' }).click()
await page.waitForTimeout(250)
await back()
check('back: after closing with X, one Back changes page (tasks → settings)', page.url().endsWith('#/settings'), page.url())
// task editor: Back saves and closes
await page.goto(URL + '#/tasks')
await page.getByRole('tab', { name: /Hoje/ }).click()
await page.getByText('Ligar para o banco').click()
await page.getByLabel('Título').fill('Ligar para o banco amanhã cedo')
await back()
s = await state()
check('back: task editor closes and saves', !(await sheetOpen()) && s.tasks.some((x) => x.title === 'Ligar para o banco amanhã cedo'))
// Mais menu → Rotinas, then Back returns to where we were, menu not reopened
await page.goto(URL + '#/clock')
await page.waitForTimeout(150)
await page.getByRole('button', { name: 'Mais opções' }).click()
await page.locator('.sheet').getByText('Rotinas').click()
await page.waitForTimeout(200)
check('back: menu navigates to Rotinas', page.url().endsWith('#/routines') && !(await sheetOpen()))
await back()
check('back: Back from Rotinas returns to Relógio in one press', page.url().endsWith('#/clock') && !(await sheetOpen()), page.url())
// bedside mode closes with Back
await page.getByRole('button', { name: 'Modo cabeceira' }).click()
await back()
check('back: Back exits bedside mode', (await page.locator('.bedside').count()) === 0 && page.url().endsWith('#/clock'))

check('no runtime errors', errors.length === 0, errors.slice(0, 3).join(' | '))
await browser.close()
for (const [r, n, e] of results) console.log(`${r}  ${n}${r === 'FAIL' && e ? '  → ' + e : ''}`)
console.log(`\n${results.filter((r) => r[0] === 'PASS').length}/${results.length} passed`)
